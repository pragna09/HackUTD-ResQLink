// Writes the deterministic SYNTHETIC dataset to seed/synthetic-data.json for inspection.
// The same generator (module/src/seed_data.ts) runs inside the module's init and reset_demo reducers,
// so this file is exactly what the database gets.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildSeedDataset } from '../module/src/seed_data';

const data = buildSeedDataset();
const out = new URL('./synthetic-data.json', import.meta.url);
writeFileSync(out, JSON.stringify({ _note: 'ALL DATA IS SYNTHETIC. Generated by module/src/seed_data.ts.', ...data }, null, 2));

const inside = data.users.filter((_, i) => i < 160).length;
const silent = data.users.filter(u => u.silent);
console.log(`zone:      ${data.zone.name} (r=${data.zone.radiusKm} km)`);
console.log(`users:     ${data.users.length} (${inside} inside zone, ${data.users.length - inside} just outside)`);
console.log(`           ${silent.length} with stale heartbeats, ${data.users.filter(u => u.vulnerabilityFlag).length} vulnerable, ${data.users.filter(u => u.hasPets).length} with pets`);
console.log(`centers:   ${data.centers.length}`);
console.log(`shelters:  ${data.shelters.length} (${data.shelters.reduce((s, o) => s + o.capacity, 0)} spots)`);
console.log(`news:      ${data.news.length}`);
console.log(`wrote ${fileURLToPath(out)}`);
